// Package predictor превращает кадр прогноза в число: насколько машина
// опоздает к цели и с какой вероятностью.
//
// Внутри два независимых источника. BaselinePredictor не обращается никуда и
// возвращает cur_dev_s без изменений: это единственное предсказание, которое
// не может быть неправильным по построению. MLClient ходит в сервис модели за
// добавкой к отклонению. Fallback собирает их вместе и выбирает, чем
// ответить, когда модель недоступна.
//
// Что здесь считается ошибкой, а что нормой.
//
// Ошибка — рассинхронизация имён признаков. Если модель обучалась на двадцати
// одном признаке, а кадр уехал с двадцатью, порядок колонок в запросе
// перестаёт что-либо значить, и модель молча разбирает признаки не по names,
// а по позициям. Ответ будет правдоподобным и неверным одновременно, и
// развалится не на скоринге, а на площадке, через несколько смен. Поэтому
// MLClient сверяет /model/info с horizon.FeatureNames() до первого запроса
// прогноза и отказывается работать при расхождении, перечисляя различия.
// Fallback в этом случае уходит на baseline, то есть деградация заметна и
// измерима.
//
// Норма — недоступность модели. Таймаут, обрыв, 503, несовпадение контракта:
// всё это не повод останавливать конвейер и не повод отдавать выдуманное
// число. Fallback отдаёт последний известный прогноз с флагом устаревания, а
// если и его нет — baseline. Оба ответа честны: первое отвечает на вопрос
// «что было известно», второе — «что можно сказать без модели».
package predictor

import (
	"context"
	"time"

	"github.com/ebiskauesbi/transport-prediction/backend/internal/horizon"
)

// Source — откуда взят прогноз. Значение обязано доезжать до клиента вместе с
// числом: ответ «опоздание 240 с» без источника неотличим от выдумки.
type Source string

const (
	// SourceML — прогноз модели, полученный по HTTP.
	SourceML Source = "ml"
	// SourceBaseline — отклонение без модели: cur_dev_s как есть.
	SourceBaseline Source = "baseline"
	// SourceCached — последний удачный прогноз модели, устаревший по времени.
	SourceCached Source = "cached"
)

// Prediction — ответ на запрос «когда машина придёт к цели».
type Prediction struct {
	// SampleID — кадр, к которому относится ответ. При SourceCached это
	// SampleID того самого старого кадра, а не текущего: подставлять
	// свежий идентификатор к старому числу нельзя, иначе клиент решит,
	// что прогноз получен для только что пришедшего кадра.
	SampleID string
	// UnitID — устройство.
	UnitID uint32
	// TRID — номер транспортного средства.
	TRID int64
	// AsOf — момент, на который ответ актуален. Для SourceCached это
	// время старого кадра, и по нему видно, насколько ответ отстал.
	AsOf time.Time
	// TargetStopID — остановка-цель.
	TargetStopID int64
	// HorizonS — горизонт в секундах.
	HorizonS float64
	// DeltaS — добавка к отклонению в секундах. Для модели выводится из
	// ответа (delay_s минус cur_dev_s: сервис по ADR-0007 отдаёт сумму), для
	// baseline остаётся честным нулём: «модель ничего не добавила» и «модели
	// не было» — разные вещи, и держать их раздельно нужно именно поэтому.
	DeltaS float64
	// PredictedDevS — итоговое отклонение в секундах: cur_dev_s + DeltaS.
	PredictedDevS float64
	// PLate — вероятность опоздания в [0, 1].
	PLate float64
	// Reason — предполагаемая причина прогноза (правила §5.4 на стороне ML,
	// predictor.late.infer_reason). Пустая у baseline и fallback: объяснить
	// кадр правилом «cur_dev» нечего.
	Reason string
	// ModelVersion — версия модели, давшая ответ. Пустая у baseline.
	ModelVersion string
	// Source — откуда ответ.
	Source Source
	// Stale — ответ устарел: он достался из кэша, потому что модель
	// недоступна. Отдельный флаг, а не вывод из Source, потому что
	// устаревание — свойство данных, а не происхождения.
	Stale bool
	// Missing — признаки, которые в кадре не измерены. Модель обучена
	// терпеть пропуски, но потребителю прогноза полезно знать, что
	// качество кадра было неполным.
	Missing []string
	// Latency — сколько занял ответ. Для baseline ноль: сетевого
	// обращения не было, и замерять тут нечего.
	Latency time.Duration
}

// Predictor превращает кадр в прогноз.
type Predictor interface {
	// Predict не возвращает ошибку наружу. Отказ модели — это деградация,
	// которой занимается Fallback, а не повод падать на каждый кадр
	// конвейера. Предиктора, который умеет отказаться, тут нет намеренно.
	Predict(ctx context.Context, f horizon.Frame) Prediction
}

// Batcher — предиктор, умеющий ответить на несколько кадров одним
// обращением.
//
// Отдельный интерфейс, а не второй метод в Predictor, по трём причинам.
// BaselinePredictor батчить нечего: там арифметика, и группировка кадров
// только раздует код. Моки в тестах не должны уметь то, что не требуется для
// проверки их собственной логики. И Predictor остаётся тем, чем его выбрали
// для горячего пути конвейера: предсказателем, который не возвращает ошибку
// наружу.
//
// Контракт жёсткий: либо ровно len(frames) прогнозов в том же порядке, либо
// ошибка. Порядок и длина — часть контракта, а не деталь: планировщик
// раздаёт ответы по кадрам один в один, и «примерно столько же» здесь
// означает «чей-то прогноз попал на чужую машину».
type Batcher interface {
	// PredictBatch возвращает прогнозы в порядке кадров. Отказ возвращается
	// ошибкой, а не укороченным срезом: вызывающий сам решит, стоит ли
	// пройти эти кадры по одному.
	PredictBatch(ctx context.Context, frames []horizon.Frame) ([]Prediction, error)
}

// contractNames — имена признаков, которые модель обязана уметь принимать.
// Объявлено отдельно от horizon.FeatureNames(), чтобы пакет не зависел от
// внутреннего устройства раскладки кадра: контракт с моделью живёт здесь и
// проверяется здесь же.
var contractNames = horizon.FeatureNames()

// FeatureContract возвращает имена признаков, которые Predictor обещает
// отдать модели. Gateway сверяет этот список с /model/info при старте и
// показывает расхождение в /readyz, а не ждёт первого прогноза.
func FeatureContract() []string {
	out := make([]string, len(contractNames))
	copy(out, contractNames)
	return out
}
